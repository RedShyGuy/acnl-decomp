// the pure attributes of the parts of a unit: 0-3 the triangles from the center to the north, west, south and east side
// (like JmpUnit::Side), 4-7 (name is ours)
struct FieldAttributeParts {
    FieldAttribute parts[8];
};
ASSERT_SIZE(FieldAttributeParts, 0x8);

// The properties of the attributes (the tables of dFieldAttribute.cpp; the names are ours, the tables whose meaning is
// not known yet are named after their address). An attribute out of range reads entry 0 (the parts: 0xFF).
