bool HasAttributeFlag02(FieldAttribute attribute); // 0x005CEA38
bool HasAttributeFlag04(FieldAttribute attribute); // 0x005CED58
bool HasAttributeFlag08(FieldAttribute attribute); // 0x005CEA68
s8 GetAttribute95E740(FieldAttribute attribute); // 0x005CEE0C
u8 GetAttribute95E83F(FieldAttribute attribute); // 0x005CED88
u8 GetAttribute95E93E(FieldAttribute attribute); // 0x005CEC0C
u8 GetAttribute95EA3D(FieldAttribute attribute); // 0x005CEC24
u8 GetAttribute95EB3C(FieldAttribute attribute); // 0x005CEA88
u8 GetAttribute95EC3B(FieldAttribute attribute); // 0x005CEBE4
u8 GetAttribute89155C(FieldAttribute attribute); // 0x005CEAA0
