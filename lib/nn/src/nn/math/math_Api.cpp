nn::math::VEC3* VEC3SafeNormalize(nn::math::VEC3* pOut, const nn::math::VEC3* pV, const nn::math::VEC3& alt)
{
    f32 lengthSquare = pV->x * pV->x + pV->y * pV->y + pV->z * pV->z;
    if (lengthSquare == 0.0f) {
        *pOut = alt;
        return pOut;
    }
    f32 inverse = 1.0f / sqrtf(lengthSquare);
    pOut->x = pV->x * inverse;
    pOut->y = pV->y * inverse;
    pOut->z = pV->z * inverse;
    return pOut;
}

