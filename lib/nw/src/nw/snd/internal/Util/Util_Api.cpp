const void* GetWaveFileOfWaveSound(const void* pWaveSoundFile, u32 index, const SoundArchive& archive, const SoundArchiveLoader& loader)
{
    WaveSoundFileReader reader(pWaveSoundFile);
    WaveSoundNoteInfo noteInfo;
    reader.ReadNoteInfo(&noteInfo, index, 0);
    const void* pWaveArchiveFile = loader.detail_GetFileAddressByItemId(noteInfo.waveArchiveId);
    if (pWaveArchiveFile == nullptr) {
        return nullptr;
    }
    SoundArchive::WaveArchiveInfo info;
    info.fileId = 0xFFFFFFFF;
    info.isLoadIndividual = false;
    archive.ReadWaveArchiveInfo(noteInfo.waveArchiveId, &info);
    WaveArchiveFileReader waveArchiveReader(pWaveArchiveFile, info.isLoadIndividual);
    return waveArchiveReader.GetWaveFile(noteInfo.waveIndex);
}

