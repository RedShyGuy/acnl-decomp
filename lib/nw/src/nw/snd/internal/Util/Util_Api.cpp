// 0x004C9BF8 | nintendogs:bytes [tier A]
u16 CalcLpfFreq(f32 scale)
{
    scale = Clamp(scale, 0.0f, 1.0f);
    if (scale < LPF_SCALE_MIN) {
        return 80;
    }
    if (scale >= LPF_SCALE_MAX) {
        return 16000;
    }
    return s_LpfFreqTable[static_cast<int>((scale - LPF_SCALE_MIN) * LPF_TABLE_STEPS_PER_SCALE)];
}

// 0x004C9C90 | fefates:bytes [tier B]
f32 CalcPanRatio(f32 pan, const PanInfo& panInfo)
{
    pan = Clamp(pan, -1.0f, 1.0f);
    const f32 position = (pan + 1.0f) * 0.5f;
    const f32* pTable;
    if (!panInfo.isSurroundIgnored && driver::HardwareManager::GetInstance().GetOutputMode() == OUTPUT_MODE_SURROUND) {
        pTable = s_SurroundPanTables[panInfo.curve];
    } else {
        pTable = s_PanTables[panInfo.curve];
    }
    f32 ratio = GetPanTableValue(pTable, position);
    if (panInfo.isCenterOne) {
        ratio /= pTable[128];
    }
    if (panInfo.isClampedToOne) {
        return Clamp(ratio, 0.0f, 1.0f);
    }
    return Clamp(ratio, 0.0f, 2.0f);
}

// 0x004C9D98 | nintendogs:bytes [tier A]
f32 CalcPitchRatio(int pitch)
{
    int octave = 0;
    while (pitch < 0) {
        --octave;
        pitch += PITCH_DIVISION_RANGE;
    }
    while (pitch >= PITCH_DIVISION_RANGE) {
        ++octave;
        pitch -= PITCH_DIVISION_RANGE;
    }

    f32 ratio = 1.0f;
    while (octave > 0) {
        ratio *= 2.0f;
        --octave;
    }
    while (octave < 0) {
        ratio *= 0.5f;
        ++octave;
    }

    const int semitone = pitch / 256;
    const int fine = pitch % 256;
    if (semitone != 0) {
        ratio *= s_SemitoneRatioTable[semitone];
    }
    if (fine != 0) {
        ratio *= s_FineRatioTable[fine];
    }
    return ratio;
}

// 0x004C9EC4 | nintendogs:bytes [tier A]
f32 CalcVolumeRatio(f32 dB)
{
    dB = Clamp(dB, VOLUME_MIN_DB, VOLUME_MAX_DB);
    return s_VolumeRatioTable[static_cast<int>(dB * 10.0f) + VOLUME_TABLE_ZERO_DB];
}

// 0x004C9F1C | nintendogs:bytes [tier A]
u32 GetByteBySample(u32 samples, SampleFormat format)
{
    switch (format) {
    case SAMPLE_FORMAT_PCM_S8:
        return samples;
    case SAMPLE_FORMAT_PCM_S16:
        return samples * 2;
    case SAMPLE_FORMAT_DSP_ADPCM: {
        // 8 bytes per frame of 14 samples: a header byte and 2 samples per byte
        u32 size = samples / 14 * 8;
        const u32 rest = samples % 14;
        if (rest != 0) {
            size += (rest + 1) / 2 + 1;
        }
        return size;
    }
    default:
        return 0;
    }
}

// 0x004C9F8C | nintendogs:bytes [tier A]
f32 CalcSurroundPanRatio(f32 pan, const PanInfo& panInfo)
{
    pan = Clamp(pan, 0.0f, 2.0f);
    const f32 ratio = GetPanTableValue(s_PanTables[panInfo.curve], pan * 0.5f);
    return Clamp(ratio, 0.0f, 2.0f);
}

// 0x004CA014 | fefates:bytes [tier B]
int GetWaveArchiveOfBank(LoadItemInfo& loadItemInfo, bool& isLoadIndividual, const void* pBankFile, const SoundArchive& archive, const SoundArchiveLoader& loader)
{
    loadItemInfo.itemId = 0xFFFFFFFF;
    loadItemInfo.address = nullptr;
    isLoadIndividual = false;

    BankFileReader bankReader(pBankFile);
    const BinaryTable<WaveId>* pWaveIdTable = bankReader.GetWaveIdTable();
    if (pWaveIdTable == nullptr) {
        return WAVE_ARCHIVE_OF_BANK_NO_TABLE;
    }
    if (pWaveIdTable->count == 0) {
        return WAVE_ARCHIVE_OF_BANK_NO_WAVES;
    }
    // all waves of a bank are in one wave archive
    const WaveId* pWaveId = pWaveIdTable->count > 0 ? &pWaveIdTable->items[0] : nullptr;
    if (pWaveId == nullptr) {
        return WAVE_ARCHIVE_OF_BANK_NO_TABLE;
    }
    const void* pWaveArchiveFile = loader.detail_GetFileAddressByItemId(pWaveId->waveArchiveId);
    if (pWaveArchiveFile == nullptr) {
        return WAVE_ARCHIVE_OF_BANK_NOT_LOADED;
    }
    SoundArchive::WaveArchiveInfo info;
    info.fileId = 0xFFFFFFFF;
    info.isLoadIndividual = false;
    archive.ReadWaveArchiveInfo(pWaveId->waveArchiveId, &info);
    loadItemInfo.itemId = pWaveId->waveArchiveId;
    loadItemInfo.address = pWaveArchiveFile;
    isLoadIndividual = info.isLoadIndividual;
    if (!info.isLoadIndividual) {
        return WAVE_ARCHIVE_OF_BANK_LOADED;
    }

    // individually loaded: the waves must be there (the original tests the first wave each time)
    WaveArchiveFileReader waveArchiveReader(pWaveArchiveFile, true);
    for (u32 i = 0; i < pWaveIdTable->count; ++i) {
        if (!waveArchiveReader.m_IsInitialized || waveArchiveReader.GetWaveFile(pWaveId->waveIndex) == nullptr) {
            return WAVE_ARCHIVE_OF_BANK_WAVE_MISSING;
        }
    }
    return WAVE_ARCHIVE_OF_BANK_LOADED;
}

