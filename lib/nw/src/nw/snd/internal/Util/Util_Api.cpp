const f32 VOLUME_MIN_DB = -90.4f;
const f32 VOLUME_MAX_DB = 6.0f;
const int VOLUME_TABLE_ZERO_DB = 904;

// the pitch steps of an octave
const int PITCH_DIVISION_RANGE = 12 * 256;

// (inline) the value within [min, max]
inline f32 Clamp(f32 value, f32 min, f32 max)
{
    if (value > max) {
        return max;
    }
    if (value < min) {
        return min;
    }
    return value;
}

// (inline) the entry of a pan table for a position 0 to 1
inline f32 GetPanTableValue(const f32* pTable, f32 position)
{
    return pTable[static_cast<int>(position * 256 + 0.5f)];
}
