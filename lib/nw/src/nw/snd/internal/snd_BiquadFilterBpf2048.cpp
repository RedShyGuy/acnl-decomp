// 0x0074085C slot 0x08 (name after BiquadFilterBpf512)
void nw::snd::internal::BiquadFilterBpf2048::GetCoefficients(int /*type*/, f32 value, nn::snd::CTR::BiquadFilterCoefficients* pCoefficients) const
{
    int index = static_cast<int>((2.0f - value) * value * 92.0f);
    if (index > 92) {
        index = 92;
    } else if (index < 0) {
        index = 0;
    }
    *pCoefficients = s_Bpf2048CoefficientsTable[index];
}

