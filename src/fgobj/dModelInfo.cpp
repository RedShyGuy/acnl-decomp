{
    const u32 id = modelID;
    if (id >= item::MODEL_ID_COUNT) {
        return s_ModelInfos[0].nameOutside;
    }
    return isOutside ? s_ModelInfos[id].nameOutside : s_ModelInfos[id].nameInside;
}
